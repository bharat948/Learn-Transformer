"""
RLCD (Reinforcement Learning for Calibrated Decisions) Fine-Tuning Module.

Optimizes the JEV decision model using REINFORCE / Policy Gradient with dual objectives:
1. Decision Financial Payoff / Reward (Return generated by selected market actions).
2. Calibration Penalty (Brier Score / ECE penalization for miscalibrated overconfidence).
"""

import os
import torch
import torch.nn as nn
import torch.nn.functional as F
from torch.distributions import Categorical
from model import JEVModel
from train_supervised import compute_brier_score, compute_expected_calibration_error


def calculate_financial_reward(actions: torch.Tensor, forward_returns: torch.Tensor) -> torch.Tensor:
    """
    Computes financial return reward based on actions taken:
    - Action 0 (Risk-Off / Short/Cash): Multiplies negative return by -1 (short profit) or earns 0.0 risk-free rate.
    - Action 1 (Neutral / Hold): Gains 0.2x market exposure.
    - Action 2 (Risk-On / Long): Gains 1.0x forward return.
    """
    rewards = torch.zeros_like(forward_returns)

    # Action 0 (Risk-Off): Short or safe cash yield
    rewards[actions == 0] = -0.5 * forward_returns[actions == 0] + 0.0001

    # Action 1 (Neutral): Reduced exposure
    rewards[actions == 1] = 0.2 * forward_returns[actions == 1]

    # Action 2 (Risk-On): Full market exposure
    rewards[actions == 2] = 1.0 * forward_returns[actions == 2]

    return rewards


def train_rlcd(
    dataset_path: str = "jev-rlcd/data/transformed_dataset.pt",
    pretrained_checkpoint: str = "jev-rlcd/checkpoints/jev_finetuned.pt",
    rlcd_checkpoint: str = "jev-rlcd/checkpoints/jev_rlcd.pt",
    epochs: int = 25,
    lr: float = 3e-4,
    calibration_penalty_weight: float = 1.5
):
    os.makedirs(os.path.dirname(rlcd_checkpoint), exist_ok=True)

    dataset = torch.load(dataset_path)
    X_train, Y_train, R_train = dataset["X_train"], dataset["Y_train"], dataset["R_train"]
    X_test, Y_test, R_test = dataset["X_test"], dataset["Y_test"], dataset["R_test"]

    model = JEVModel(feature_dim=dataset["feature_dim"])

    if os.path.exists(pretrained_checkpoint):
        ckpt = torch.load(pretrained_checkpoint)
        model.load_state_dict(ckpt["model_state"])
        print(f"[RLCD] Loaded pre-trained weights from {pretrained_checkpoint}")
    else:
        print("[RLCD] Pre-trained checkpoint not found, initializing from scratch.")

    optimizer = torch.optim.AdamW(model.parameters(), lr=lr, weight_decay=1e-4)

    print(f"=== Starting RLCD Reinforcement Learning Fine-Tuning ({epochs} Epochs) ===")

    best_cumulative_reward = float("-inf")

    batch_size = 64
    num_samples = len(X_train)

    for epoch in range(1, epochs + 1):
        model.train()

        # Shuffle indices
        indices = torch.randperm(num_samples)
        epoch_policy_loss = 0.0
        epoch_reward = 0.0
        epoch_calib_penalty = 0.0

        for i in range(0, num_samples, batch_size):
            batch_idx = indices[i : i + batch_size]
            batch_x = X_train[batch_idx]
            batch_r = R_train[batch_idx]
            batch_y = Y_train[batch_idx]

            out = model(batch_x)
            probs = out["calibrated_probs"]

            # Sample action according to policy distribution
            dist = Categorical(probs)
            sampled_actions = dist.sample()
            log_probs = dist.log_prob(sampled_actions)

            # Calculate decision payoff rewards
            financial_rewards = calculate_financial_reward(sampled_actions, batch_r)

            # Calibration penalty: discrepancy between decision probability and outcome ground truth
            brier_penalty = compute_brier_score(probs, batch_y)

            # Combined advantage/reward signal: Financial Reward - Calibration Penalty (detached for REINFORCE return weighting)
            adjusted_rewards = (financial_rewards - calibration_penalty_weight * brier_penalty).detach()

            # Standardize rewards for variance reduction
            if len(adjusted_rewards) > 1:
                rewards_normalized = (adjusted_rewards - adjusted_rewards.mean()) / (adjusted_rewards.std() + 1e-8)
            else:
                rewards_normalized = adjusted_rewards

            # Policy gradient loss with entropy regularization + explicit calibration loss
            policy_loss = -torch.mean(log_probs * rewards_normalized) - 0.01 * torch.mean(dist.entropy()) + calibration_penalty_weight * brier_penalty

            optimizer.zero_grad()
            policy_loss.backward()
            optimizer.step()

            epoch_policy_loss += policy_loss.item() * len(batch_idx)
            epoch_reward += financial_rewards.sum().item()
            epoch_calib_penalty += brier_penalty.item() * len(batch_idx)

        avg_reward = epoch_reward / num_samples
        avg_calib = epoch_calib_penalty / num_samples

        # Evaluate Policy on Test Split
        model.eval()
        with torch.no_grad():
            test_out = model(X_test)
            test_probs = test_out["calibrated_probs"]
            test_preds = torch.argmax(test_probs, dim=1)
            test_rewards = calculate_financial_reward(test_preds, R_test)
            test_acc = (test_preds == Y_test).float().mean().item()
            test_ece = compute_expected_calibration_error(test_probs, Y_test)
            test_cum_reward = test_rewards.sum().item()

        if epoch % 5 == 0 or epoch == epochs:
            print(f"Epoch {epoch:02d}/{epochs:02d} | Train Reward: {avg_reward:.4f} | Test Return: {test_cum_reward:.4f} Test Acc: {test_acc:.4f} Test ECE: {test_ece:.4f}")

        if test_cum_reward > best_cumulative_reward:
            best_cumulative_reward = test_cum_reward
            torch.save({
                "model_state": model.state_dict(),
                "feature_dim": dataset["feature_dim"],
                "scaler_mean": dataset["scaler_mean"],
                "scaler_std": dataset["scaler_std"],
                "test_acc": test_acc,
                "test_ece": test_ece,
                "test_cumulative_reward": test_cum_reward
            }, rlcd_checkpoint)

    print(f"[RLCD] Fine-tuning complete! Saved best RLCD checkpoint to {rlcd_checkpoint}")


if __name__ == "__main__":
    train_rlcd()
